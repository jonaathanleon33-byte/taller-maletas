// Para comparar sin importar mayúsculas ni tildes ("velez" encuentra "Vélez").
export function normalizarMarca(texto: string) {
  return texto
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .trim();
}
