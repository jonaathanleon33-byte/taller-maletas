-- Cotizaciones de reparación. Tienen su propia numeración (COT-0001…)
-- y NO usan el consecutivo de recibos ni el de ventas: una cotización
-- no es una factura y puede no convertirse nunca en una orden.
create table cotizaciones (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cliente_nombre text not null,
  cliente_telefono text not null,
  descripcion text not null,
  notas text,
  descuento_global numeric(12, 2) not null default 0,
  incluye_iva boolean not null default false,
  vigencia_hasta date,
  estado text not null default 'pendiente' check (estado in ('pendiente', 'aprobada', 'rechazada'))
);

create table cotizacion_items (
  id uuid primary key default gen_random_uuid(),
  cotizacion_id uuid not null references cotizaciones(id) on delete cascade,
  servicio_id uuid references servicios(id) on delete set null,
  descripcion text not null,
  precio_unitario numeric(12, 2) not null default 0,
  cantidad integer not null default 1,
  descuento_pct numeric(5, 2) not null default 0,
  created_at timestamptz not null default now()
);

create index cotizaciones_created_idx on cotizaciones (created_at desc);
create index cotizacion_items_cotizacion_idx on cotizacion_items (cotizacion_id);

alter table cotizaciones enable row level security;
alter table cotizacion_items enable row level security;

create policy "cotizaciones_anon_all" on cotizaciones
  for all to anon, authenticated using (true) with check (true);
create policy "cotizacion_items_anon_all" on cotizacion_items
  for all to anon, authenticated using (true) with check (true);

create or replace function set_cotizaciones_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger cotizaciones_updated_at
  before update on cotizaciones
  for each row execute function set_cotizaciones_updated_at();
